// Lógica pura del módulo Portapapeles de Utilidades (fase 43): el historial, qué copias no se guardan, el estado del permiso que pide
// macOS, los colores y dónde está cada cosa para dibujarla y resolver los clics. Nada de aquí toca el portapapeles: `ClipboardStore`
// lo lee y lo escribe.

// MARK: - Historial

struct ClipboardEntry: Equatable, Identifiable, Codable, Sendable {
    var id = UUID().uuidString
    var text: String
    var date: Date
}

/// Lo que se copió, del más nuevo al más viejo: 20 en memoria y 6 a la vista
struct ClipboardHistory: Equatable, Sendable {
    static let capacity = 20
    static let visibleCount = 6
    /// Un texto de más bytes no se guarda: 20 copias de varios megabytes llenarían la memoria. Se miden bytes, no caracteres: contar
    /// los caracteres de un texto enorme recorre todo el texto, y los bytes ya los sabe
    static let maxTextLength = 100_000

    private(set) var entries: [ClipboardEntry]

    /// Lo que viene de fuera (el archivo del historial) pasa por las mismas reglas que una copia nueva: sin textos vacíos, demasiado
    /// largos ni repetidos, con identificadores distintos, y como mucho 20
    init(entries: [ClipboardEntry] = []) {
        var texts: Set<String> = []
        var ids: Set<String> = []
        var kept: [ClipboardEntry] = []
        for var entry in entries where Self.isStorable(entry.text) && texts.insert(entry.text).inserted {
            if !ids.insert(entry.id).inserted {
                entry.id = UUID().uuidString
                ids.insert(entry.id)
            }
            kept.append(entry)
            if kept.count == Self.capacity { break }
        }
        self.entries = kept
    }

    private static func isStorable(_ text: String) -> Bool {
        // Lo barato primero: el tamaño antes de recorrer el texto para ver si son solo espacios
        text.utf8.count <= maxTextLength && !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
    }

    var visible: [ClipboardEntry] { Array(entries.prefix(Self.visibleCount)) }

    /// Apunta un texto. Un texto vacío, solo de espacios o demasiado largo no cuenta, y uno repetido sube arriba en vez de salir dos
    /// veces. Devuelve si se apuntó
    @discardableResult
    mutating func add(_ text: String, at date: Date) -> Bool {
        guard Self.isStorable(text) else { return false }
        entries.removeAll { $0.text == text }
        entries.insert(ClipboardEntry(text: text, date: date), at: 0)
        if entries.count > Self.capacity { entries.removeLast(entries.count - Self.capacity) }
        return true
    }

    mutating func clear() {
        entries = []
    }

    /// Una línea para la lista: sin saltos de línea ni tabuladores, sin espacios de sobra y recortada
    static func preview(_ text: String, limit: Int = 60) -> String {
        // Solo se recorre el principio: una copia de 100 KB no se parte entera para enseñar 26 caracteres
        let head = text.prefix(limit * 4)
        let line = head.split(whereSeparator: { $0.isWhitespace || $0.isNewline }).joined(separator: " ")
        let cut = head.endIndex != text.endIndex
        return line.count > limit || cut ? String(line.prefix(limit - 1)) + "…" : line
    }
}

// MARK: - Qué no se guarda

enum ClipboardFilter {
    /// Lo que los gestores de contraseñas y otras apps ponen en una copia para decir «no la guardes»: oculta (una contraseña),
    /// pasajera o generada sola. Es una convención (nspasteboard.org) y la respetan 1Password, Bitwarden, KeePassXC y más
    static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type",
    ]

    /// Apps de las que no se guarda nada aunque no marquen la copia
    static let defaultIgnoredApps = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx", "com.bitwarden.desktop",
        "org.keepassxc.keepassxc", "org.keepassx.keepassx", "com.dashlane.dashlanephonefinal", "com.lastpass.lastpassmacdesktop",
        "com.apple.Passwords", "com.apple.keychainaccess", "com.enpass.Enpass-Desktop", "com.nordsec.nordpass",
    ]

    static func shouldSkip(types: [String], sourceBundleID: String?, ignoredApps: Set<String>) -> Bool {
        if types.contains(where: { concealedTypes.contains($0) }) { return true }
        if let sourceBundleID, ignoredApps.contains(sourceBundleID) { return true }
        return false
    }
}

// MARK: - El permiso de macOS

/// Cómo trata macOS el acceso de YabaiBar al portapapeles. Desde macOS 15.4, leerlo por programa (sin que pegues) pregunta al usuario;
/// `unasked` es antes de la primera pregunta
enum ClipboardAccessBehavior: Equatable, Sendable {
    case unasked, ask, alwaysAllow, alwaysDeny
}

/// Qué dice el módulo en modo Historial
enum ClipboardHistoryState: Equatable, Sendable {
    /// Apagado: no mira nada
    case off
    /// Encendido y con permiso: apunta lo que copias
    case recording
    /// Encendido pero macOS todavía no ha preguntado: un clic pide el acceso
    case needsFirstAccess
    /// macOS pregunta cada vez que se lee: no se lee solo hasta que el usuario elija «Permitir» en Ajustes del Sistema
    case needsAllow
    case denied

    static func make(enabled: Bool, behavior: ClipboardAccessBehavior) -> ClipboardHistoryState {
        guard enabled else { return .off }
        switch behavior {
        case .alwaysAllow: return .recording
        case .unasked: return .needsFirstAccess
        case .ask: return .needsAllow
        case .alwaysDeny: return .denied
        }
    }
}

// MARK: - Colores

struct RGBColor: Equatable, Sendable {
    var red: Double
    var green: Double
    var blue: Double
}

enum ColorHex {
    /// «#1A2B3C»
    static func string(_ color: RGBColor) -> String {
        func byte(_ value: Double) -> Int { min(255, max(0, Int((value * 255).rounded()))) }
        return String(format: "#%02X%02X%02X", byte(color.red), byte(color.green), byte(color.blue))
    }

    /// El color de «#1A2B3C» (con o sin la almohadilla); nil si no son 6 cifras hexadecimales
    static func color(_ hex: String) -> RGBColor? {
        let digits = hex.hasPrefix("#") ? String(hex.dropFirst()) : hex
        // Solo cifras hexadecimales: `Int(radix:)` también deja pasar un signo («+1A2B3»)
        guard digits.count == 6, digits.allSatisfy({ $0.isASCII && $0.isHexDigit }), let value = Int(digits, radix: 16) else { return nil }
        return RGBColor(
            red: Double((value >> 16) & 0xFF) / 255, green: Double((value >> 8) & 0xFF) / 255, blue: Double(value & 0xFF) / 255
        )
    }

    static func isValid(_ hex: String) -> Bool {
        hex.hasPrefix("#") && color(hex) != nil
    }
}

/// Las muestras de los últimos colores elegidos
struct ClipboardColors: Equatable, Sendable {
    static let capacity = 8

    private(set) var hexes: [String]

    /// Lo guardado se valida: lo que no es un color se descarta
    init(hexes: [String] = []) {
        var seen: Set<String> = []
        self.hexes = hexes.map { $0.uppercased() }.filter { ColorHex.isValid($0) && seen.insert($0).inserted }.prefix(Self.capacity).map { $0 }
    }

    mutating func add(_ hex: String) {
        let hex = hex.uppercased()
        guard ColorHex.isValid(hex) else { return }
        hexes.removeAll { $0 == hex }
        hexes.insert(hex, at: 0)
        if hexes.count > Self.capacity { hexes.removeLast(hexes.count - Self.capacity) }
    }
}

// MARK: - Lo que enseña el módulo

enum ClipboardMode: String, Equatable, Sendable {
    case history, tools
}

/// La confirmación de una herramienta («JSON formateado») o su error, un par de segundos en la cabecera
struct ClipboardMessage: Equatable, Sendable {
    var text: String
    var isError: Bool
}

struct ClipboardSnapshot: Equatable, Sendable {
    struct Row: Equatable, Identifiable, Sendable {
        var id: String
        var preview: String
    }

    var mode: ClipboardMode
    var state: ClipboardHistoryState
    var rows: [Row]
    var colors: [String]
    var message: ClipboardMessage?

    static func make(
        mode: ClipboardMode, state: ClipboardHistoryState, history: ClipboardHistory, colors: ClipboardColors, message: ClipboardMessage?
    ) -> ClipboardSnapshot {
        ClipboardSnapshot(
            mode: mode, state: state,
            rows: history.visible.map { Row(id: $0.id, preview: ClipboardHistory.preview($0.text, limit: 26)) },
            colors: colors.hexes, message: message
        )
    }
}

// MARK: - Dónde está cada cosa

/// Lo que se pulsa en el módulo
enum ClipboardControl: Hashable, Sendable {
    case mode(ClipboardMode)
    /// Borrar el historial
    case clear
    /// Una de las copias de la lista (0 a 5): se vuelve a copiar
    case entry(Int)
    case tool(DevTool)
    /// El cuentagotas
    case picker
    /// Una muestra de color (0 a 7): se vuelve a copiar su valor
    case swatch(Int)
    /// «Activar el historial», «Dar acceso» o abrir Ajustes del Sistema, según el estado
    case access
}

// El módulo mide 250 × 112: la cabecera (título y los tres botones de la derecha), y debajo 76 pt. El historial son 6 copias en 2
// columnas de 3; las herramientas son 10 botones en 2 filas de 5, y debajo el cuentagotas y las 8 últimas muestras
enum ClipboardModuleLayout {
    static let padding: CGFloat = 8
    static let headerHeight: CGFloat = 14
    static let bodyY: CGFloat = 28
    static let iconSize = CGSize(width: 18, height: 14)
    static let iconSpacing: CGFloat = 4
    static let entryHeight: CGFloat = 23
    static let entryRowSpacing: CGFloat = 2
    static let toolHeight: CGFloat = 22
    static let toolSpacing: CGFloat = 4
    static let toolColumns = 5
    static let pickerSize = CGSize(width: 28, height: 22)
    static let swatchSize: CGFloat = 18
    static let swatchSpacing: CGFloat = 4
    static let accessSize = CGSize(width: 180, height: 24)

    /// Los botones de la cabecera, de derecha a izquierda: herramientas, historial y borrar
    static func toolsModeFrame(in size: CGSize) -> CGRect {
        CGRect(x: size.width - padding - iconSize.width, y: padding, width: iconSize.width, height: iconSize.height)
    }

    static func historyModeFrame(in size: CGSize) -> CGRect {
        toolsModeFrame(in: size).offsetBy(dx: -(iconSize.width + iconSpacing), dy: 0)
    }

    static func clearFrame(in size: CGSize) -> CGRect {
        historyModeFrame(in: size).offsetBy(dx: -(iconSize.width + iconSpacing), dy: 0)
    }

    static func entryFrame(_ index: Int, in size: CGSize) -> CGRect {
        let width = (size.width - 2 * padding - toolSpacing) / 2
        return CGRect(
            x: padding + CGFloat(index % 2) * (width + toolSpacing), y: bodyY + CGFloat(index / 2) * (entryHeight + entryRowSpacing),
            width: width, height: entryHeight
        )
    }

    static func toolFrame(_ index: Int, in size: CGSize) -> CGRect {
        let columns = CGFloat(toolColumns)
        let width = (size.width - 2 * padding - (columns - 1) * toolSpacing) / columns
        return CGRect(
            x: padding + CGFloat(index % toolColumns) * (width + toolSpacing),
            y: bodyY + CGFloat(index / toolColumns) * (toolHeight + toolSpacing), width: width, height: toolHeight
        )
    }

    /// La fila de debajo de las herramientas: el cuentagotas y las muestras
    private static var colorRowY: CGFloat { bodyY + 2 * (toolHeight + toolSpacing) }

    static func pickerFrame(in size: CGSize) -> CGRect {
        CGRect(x: padding, y: colorRowY, width: pickerSize.width, height: pickerSize.height)
    }

    static func swatchFrame(_ index: Int, in size: CGSize) -> CGRect {
        CGRect(
            x: padding + pickerSize.width + 8 + CGFloat(index) * (swatchSize + swatchSpacing),
            y: colorRowY + (pickerSize.height - swatchSize) / 2, width: swatchSize, height: swatchSize
        )
    }

    /// El botón que ofrece activar el historial o dar acceso, centrado en el cuerpo
    static func accessFrame(in size: CGSize) -> CGRect {
        CGRect(x: (size.width - accessSize.width) / 2, y: bodyY + 36, width: accessSize.width, height: accessSize.height)
    }

    /// Lo que hay bajo un punto del módulo (origen arriba a la izquierda). Con un poco de margen en los botones pequeños
    static func control(
        at point: CGPoint, in size: CGSize, mode: ClipboardMode, state: ClipboardHistoryState, entryCount: Int, swatchCount: Int
    ) -> ClipboardControl? {
        if toolsModeFrame(in: size).insetBy(dx: -2, dy: -4).contains(point) { return .mode(.tools) }
        if historyModeFrame(in: size).insetBy(dx: -2, dy: -4).contains(point) { return .mode(.history) }
        if mode == .history, state == .recording, entryCount > 0, clearFrame(in: size).insetBy(dx: -2, dy: -4).contains(point) { return .clear }
        switch mode {
        case .history:
            if state != .recording {
                return accessFrame(in: size).insetBy(dx: -4, dy: -4).contains(point) ? .access : nil
            }
            for index in 0..<min(entryCount, ClipboardHistory.visibleCount) where entryFrame(index, in: size).contains(point) {
                return .entry(index)
            }
        case .tools:
            for (index, tool) in DevTool.allCases.enumerated() where toolFrame(index, in: size).contains(point) { return .tool(tool) }
            if pickerFrame(in: size).contains(point) { return .picker }
            for index in 0..<min(swatchCount, ClipboardColors.capacity) where swatchFrame(index, in: size).insetBy(dx: -2, dy: -2).contains(point) {
                return .swatch(index)
            }
        }
        return nil
    }
}

extension IslandExpandedLayout {
    /// El módulo Portapapeles, en coordenadas de la isla (origen arriba a la izquierda). Solo existe en Utilidades
    func clipboardFrame(islandWidth: CGFloat, topHeight: CGFloat) -> CGRect? {
        guard tab == .utilities, let cell = utilityModules.cells.first(where: { $0.module == .clipboard }) else { return nil }
        let origin = activityOrigin(islandWidth: islandWidth, topHeight: topHeight)
        return cell.frame.offsetBy(dx: origin.x, dy: origin.y + Self.activityHeight + Self.activityGap)
    }

    func clipboardControl(
        at point: CGPoint, islandWidth: CGFloat, topHeight: CGFloat, mode: ClipboardMode, state: ClipboardHistoryState,
        entryCount: Int, swatchCount: Int
    ) -> ClipboardControl? {
        guard let frame = clipboardFrame(islandWidth: islandWidth, topHeight: topHeight), frame.contains(point) else { return nil }
        return ClipboardModuleLayout.control(
            at: CGPoint(x: point.x - frame.minX, y: point.y - frame.minY), in: frame.size, mode: mode, state: state,
            entryCount: entryCount, swatchCount: swatchCount
        )
    }
}
